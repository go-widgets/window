//go:build ignore

// gen_table writes table_windows_arm64.s: Slots entries of two instructions
// each, `MOVD $i, R16; B cbCommon`, so that entry i sits at cbEntries+8*i. The
// runtime's own zcallback_windows_arm64.s is built the same way.
package main

import (
	"bytes"
	"fmt"
	"os"
)

const slots = 256 // keep equal to wincb.Slots; the test checks it

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_table.go; DO NOT EDIT.\n\n")
	b.WriteString("//go:build windows && arm64\n\n")
	b.WriteString("#include \"textflag.h\"\n\n")
	b.WriteString("// Entry i is MOVD $i, R16 then B cbCommon: exactly 8 bytes each.\n")
	b.WriteString("TEXT ·cbEntries(SB),NOSPLIT|NOFRAME,$0-0\n")
	for i := 0; i < slots; i++ {
		fmt.Fprintf(&b, "\tMOVD\t$%d, R16\n\tB\t·cbCommon(SB)\n", i)
	}
	if err := os.WriteFile("table_windows_arm64.s", b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
